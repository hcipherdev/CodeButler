import { createHash, randomUUID } from "node:crypto";
import { assertOrdinaryProject } from "../rules/identity.js";
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, renameSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { MemoryStore } from "../storage/store.js";
import type { MemorySearchResult } from "../types.js";
import { readMemoryKnowledge } from "./knowledge.js";
import { handbookMemories, resolveTopics, topicMatches } from "./topics.js";
import { presentMemory, presentMemoryMarkdown } from "./presentation.js";
import { isSensitiveGitPath } from "../sources/sensitive-path.js";
const hash = (text: string) => createHash("sha256").update(text).digest("hex");
const manifestName = "handbook-export.meta.json";
const header = "<!-- Generated by Code Butler. Edit project memories and export again; do not edit this document. -->\n\n";
const typeFiles = { decision: "decisions.md", constraint: "constraints.md", bug_fix: "bug-fixes.md", rejected_approach: "rejected-approaches.md" } as const;
const titles = { decision: "Decisions", constraint: "Constraints", bug_fix: "Bug fixes", rejected_approach: "Rejected approaches" };
const escape = (s: string) => s.replace(/[\\`*_[\]<>#]/g, "\\$&");
const anchor = (id: string) => "memory-" + hash(id).slice(0, 20);
interface ExportManifest {
    version: 1;
    files: Record<string, string>;
}
function allowedFile(path: string) { return /^(?:index|decisions|constraints|bug-fixes|rejected-approaches)\.md$/.test(path) || /^topics\/topic-[a-f0-9-]+\.md$/.test(path); }
function safePath(base: string, path: string): string {
    const parts = path.split("/");
    if (parts.some(p => !p || p === "." || p === ".." || p.includes("\\") || p.includes(":")))
        throw new Error("Invalid handbook path");
    let target = base;
    if (existsSync(base) && lstatSync(base).isSymbolicLink())
        throw new Error("Handbook files cannot use symlinks");
    for (const part of parts) {
        target = join(target, part);
        if (existsSync(target) && lstatSync(target).isSymbolicLink())
            throw new Error("Handbook files cannot use symlinks");
    }
    return target;
}
function manifest(base: string): ExportManifest {
    const path = safePath(base, manifestName);
    if (!existsSync(path))
        return { version: 1, files: {} };
    const value = JSON.parse(readFileSync(path, "utf8")) as ExportManifest;
    if (value.version !== 1 || !value.files || Object.entries(value.files).some(([path, h]) => !allowedFile(path) || typeof h !== "string" || !/^[a-f0-9]{64}$/.test(h)))
        throw new Error("Handbook generation manifest is invalid");
    return value;
}
function publishable(m: MemorySearchResult): boolean {
    return m.relatedFiles.every(path => !isSensitiveGitPath(path) && !path.replaceAll("\\", "/").split("/").some(p => /^(?:secrets|credentials|private-keys?)$/i.test(p)) && !/^(?:[a-z]:|\/)/i.test(path));
}
function entry(store: MemoryStore, m: MemorySearchResult, link?: string) {
    const p = presentMemory(m);
    p.text = store.contentPolicy.text(p.text);
    p.applies = store.contentPolicy.text(p.applies);
    p.slots = p.slots.map(s => ({ ...s, value: store.contentPolicy.text(s.value) }));
    const sources = [...m.relatedFiles.map(path => "`" + store.contentPolicy.path(path).replaceAll("`", "") + "`"), ...m.evidence.filter(e => e.sourceType === "commit" && /^[a-f0-9]{7,64}$/i.test(e.sourceId)).map(e => "commit `" + e.sourceId.slice(0, 12) + "`")];
    return `<a id="${anchor(m.id)}"></a>\n\n` + presentMemoryMarkdown(p, link ? { link, label: "Memory" } : {}) + (sources.length ? "\n  Sources: " + [...new Set(sources)].join(" · ") : "") + "\n";
}
function atomic(path: string, text: string) {
    mkdirSync(dirname(path), { recursive: true });
    const temp = path + ".tmp-" + randomUUID();
    try {
        writeFileSync(temp, text, { encoding: "utf8", mode: 0o600, flag: "wx" });
        renameSync(temp, path);
    }
    finally {
        if (existsSync(temp))
            unlinkSync(temp);
    }
}
export function exportMemoryHandbook(store: MemoryStore, input: {
    dryRun?: boolean;
    force?: boolean;
} = {}) {
    assertOrdinaryProject(store.paths.rootDir);
    const root = store.paths.rootDir, base = safePath(root, ".code-butler"), destination = safePath(base, "handbook");
    const data = readMemoryKnowledge(store), eligible = handbookMemories(data, { reach: "project" }), memories = eligible.filter(publishable);
    const topics = resolveTopics(data.topics).filter(t => t.layer === "core" && !t.deleted && t.prefixes.every(p => !isSensitiveGitPath(p) && !p.split("/").some(s => /^(secrets|credentials)$/i.test(s))));
    const files: Record<string, string> = {};
    for (const [type, file] of Object.entries(typeFiles))
        files[file] = header + "# " + titles[type as keyof typeof titles] + "\n\n" + memories.filter(m => m.type === type).map(m => entry(store, m)).join("\n");
    for (const topic of topics) {
        const path = "topics/" + topic.id + ".md";
        if (!allowedFile(path))
            continue;
        const items = memories.filter(m => topicMatches(topic, m, data.overrides));
        files[path] = header + "# " + escape(store.contentPolicy.text(topic.name)) + "\n\n" + escape(store.contentPolicy.text(topic.introduction)) + "\n\n" +
            Object.entries(typeFiles).map(([type, file]) => "## " + titles[type as keyof typeof titles] + "\n\n" + items.filter(m => m.type === type).map(m => entry(store, m, "../" + file + "#" + anchor(m.id))).join("\n")).join("\n");
    }
    files["index.md"] = header + "# Project Handbook\n\n" + Object.entries(typeFiles).map(([type, file]) => `- [${titles[type as keyof typeof titles]}](${file})`).join("\n") + "\n\n## Topics\n\n" + topics.filter(t => files["topics/" + t.id + ".md"]).map(t => `- [${escape(store.contentPolicy.text(t.name))}](topics/${t.id}.md)`).join("\n") + "\n";
    const prior = manifest(base), changed: string[] = [], removed: string[] = [], blocked: string[] = [];
    for (const [path, text] of Object.entries(files)) {
        const target = safePath(destination, path);
        if (!existsSync(target)) {
            changed.push(path);
            continue;
        }
        const actual = hash(readFileSync(target, "utf8"));
        if (actual === hash(text))
            continue;
        if (actual !== prior.files[path] && !input.force)
            blocked.push(path);
        changed.push(path);
    }
    for (const path of Object.keys(prior.files))
        if (!files[path] && existsSync(safePath(destination, path))) {
            if (hash(readFileSync(safePath(destination, path), "utf8")) === prior.files[path])
                removed.push(path);
            else
                blocked.push(path);
        }
    const result = { directory: destination, memories: memories.length, excludedMemories: eligible.length - memories.length, excludedTopics: resolveTopics(data.topics).filter(t => t.layer === "core" && !t.deleted).length - topics.length, files: Object.keys(files).sort(), changed, removed, blocked, dryRun: !!input.dryRun };
    if (input.dryRun)
        return result;
    if (blocked.length)
        throw new Error("Handbook has edited or unmanaged files: " + blocked.join(", ") + ". Review them before exporting; --force backs up files being replaced.");
    const ignore = safePath(base, ".gitignore"), current = existsSync(ignore) ? readFileSync(ignore, "utf8") : "/*\n!/.gitignore\n!/project-summary.md\n";
    const start = "# code-butler:handbook begin", end = "# code-butler:handbook end";
    const clean = current.replace(/\n?# code-butler:handbook begin[\s\S]*?# code-butler:handbook end\n?/g, "\n").trimEnd();
    const next = clean + "\n\n" + [start, "/handbook-export.meta.json", "/backups/handbook/", "!/handbook/", "/handbook/*", ...Object.keys(files).filter(path => !path.includes("/")).sort().map(path => "!/handbook/" + path), "!/handbook/topics/", "/handbook/topics/*", ...Object.keys(files).filter(path => path.startsWith("topics/")).sort().map(path => "!/handbook/" + path), end, ""].join("\n");
    if (input.force)
        for (const path of changed) {
            const target = safePath(destination, path);
            if (existsSync(target) && hash(readFileSync(target, "utf8")) !== prior.files[path])
                atomic(safePath(base, "backups/handbook/" + randomUUID() + ".md"), readFileSync(target, "utf8"));
        }
    for (const path of changed)
        atomic(safePath(destination, path), files[path]!);
    for (const path of removed)
        unlinkSync(safePath(destination, path));
    if (next !== current)
        atomic(ignore, next);
    const serialized = JSON.stringify({ version: 1, files: Object.fromEntries(Object.entries(files).map(([path, text]) => [path, hash(text)])) }, null, 2) + "\n";
    const meta = safePath(base, manifestName);
    if (!existsSync(meta) || readFileSync(meta, "utf8") !== serialized)
        atomic(meta, serialized);
    return result;
}
/** Privacy removal invalidates derived publications; regular refresh remains manual. */
export function invalidateHandbookExport(root: string): void {
    const base = safePath(root, ".code-butler");
    const path = safePath(base, manifestName);
    if (!existsSync(path))
        return;
    const previous = manifest(base), destination = safePath(base, "handbook");
    for (const file of Object.keys(previous.files)) {
        const target = safePath(destination, file);
        if (existsSync(target))
            unlinkSync(target);
    }
    unlinkSync(path);
}
/** Explicit privacy backup purge includes private copies of force-replaced exports. */
export function purgeHandbookExportBackups(root: string): import("../privacy/backup.js").BackupPurgeResult {
    const result: import("../privacy/backup.js").BackupPurgeResult = { removed: [], failed: [] };
    const base = safePath(root, ".code-butler"), directory = safePath(base, "backups/handbook");
    if (!existsSync(directory))
        return result;
    for (const name of readdirSync(directory)) {
        if (!/^[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}\.md$/i.test(name))
            continue;
        const target = join(directory, name);
        if (!lstatSync(target).isFile() || lstatSync(target).isSymbolicLink())
            continue;
        try {
            unlinkSync(target);
            result.removed.push(target);
        }
        catch (error) {
            result.failed.push({ path: target, error: error instanceof Error ? error.message : String(error) });
        }
    }
    return result;
}
