// Tests actual Git ingestion of handbook-only and mixed commits to prevent generated-memory feedback loops.
import { afterEach, expect, it } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { openMemoryStore } from "../../src/storage/store.js";
import { rememberProjectMemory } from "../../src/memory/remember.js";
import { exportMemoryHandbook } from "../../src/memory/export.js";
import { scanGitSource, syncGitSource } from "../../src/sources/git.js";
import { ingestGitRepository } from "../../src/ingest/git.js";
import { makeTempDir, cleanupTempDir } from "../helpers/temp.js";
const roots: string[] = [], stores: ReturnType<typeof openMemoryStore>[] = [];
afterEach(() => { for (const store of stores.splice(0)) store.close(); for (const root of roots.splice(0)) cleanupTempDir(root); });
it("excludes handbook-only commits and strips generated patches from mixed commits in both Git readers", () => {
  const root = makeTempDir(); roots.push(root);
  const store = openMemoryStore(root); store.init(); stores.push(store);
  const git = (args: string[]) => execFileSync("git", args, { cwd: root, encoding: "utf8", windowsHide: true }).trim();
  git(["init", "--quiet"]); git(["config", "user.name", "Fixture"]); git(["config", "user.email", "fixture@example.com"]);
  const remember = (text: string) => rememberProjectMemory(store, { type: "decision", text, scope: { kind: "project" } });
  remember("Generated handbook claim must never become Git evidence."); exportMemoryHandbook(store);
  writeFileSync(join(root, "README.md"), "Fixture source\n");
  git(["add", "README.md", ".code-butler/.gitignore", ".code-butler/handbook"]); git(["commit", "--quiet", "-m", "Set up fixture"]);
  const initial = git(["rev-parse", "HEAD"]), config = { enabled: true, hookInstall: false, repoPath: root, maxCommits: 10, maxDiffChars: 100000 };
  store.setSyncCursor("git", "last_commit", initial);
  remember("Keep generated handbook updates out of extracted memories."); exportMemoryHandbook(store);
  git(["add", ".code-butler/handbook"]); git(["commit", "--quiet", "-m", "Refresh handbook"]);
  const onlyGenerated = scanGitSource(config, initial);
  expect(onlyGenerated.commits).toEqual([]);
  expect(syncGitSource(store, config, true, onlyGenerated).imported).toBe(0);
  expect(store.db.prepare("select count(*) n from extraction_jobs").get()).toEqual({ n: 0 });
  const cursor = git(["rev-parse", "HEAD"]);
  remember("This generated sentence should stay outside mixed commit evidence."); exportMemoryHandbook(store);
  mkdirSync(join(root, "src")); writeFileSync(join(root, "src/a.ts"), "export const enabled = true;\n");
  git(["add", "src/a.ts", ".code-butler/handbook"]); git(["commit", "--quiet", "-m", "Enable fixture feature"]);
  const mixed = scanGitSource(config, cursor);
  expect(mixed.commits).toHaveLength(1); expect(mixed.commits[0]?.changedFiles).toEqual(["src/a.ts"]);
  expect(mixed.commits[0]?.diffSummary).not.toContain("generated sentence");
  expect(ingestGitRepository(store, root).importedCommits).toBe(2);
  const rows = store.db.prepare("select changed_files_json, diff_summary from commits").all();
  expect(JSON.stringify(rows)).not.toContain(".code-butler/handbook");
  expect(JSON.stringify(rows)).not.toContain("Generated handbook claim");
}, 90000);
