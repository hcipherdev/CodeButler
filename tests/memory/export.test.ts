// Tests deterministic opt-in handbook publication, sensitive-path exclusion, file protection, and extraction boundaries.
import { afterEach, describe, expect, it } from "vitest";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import { openMemoryStore } from "../../src/storage/store.js";
import { rememberProjectMemory } from "../../src/memory/remember.js";
import { saveMemoryTopic } from "../../src/memory/topics.js";
import { exportMemoryHandbook, invalidateHandbookExport } from "../../src/memory/export.js";
import { isGeneratedMemoryPath } from "../../src/sources/sensitive-path.js";
import { makeTempDir, cleanupTempDir } from "../helpers/temp.js";
const roots: string[] = [], stores: ReturnType<typeof openMemoryStore>[] = [];
afterEach(() => { for (const s of stores.splice(0))
    s.close(); for (const r of roots.splice(0))
    cleanupTempDir(r); });
function fixture() { const root = makeTempDir(); roots.push(root); const store = openMemoryStore(root); store.init(); stores.push(store); return { root, store }; }
function add(store: ReturnType<typeof openMemoryStore>, text: string, files: string[] = [], layer = "core") { return rememberProjectMemory(store, { type: "constraint", text, relatedFiles: files, scope: { kind: "conditional", platforms: ["win32"] }, layer }).memory!; }
describe("manual Markdown handbook export", () => {
    it("does not write on dry run and generates stable applicable Markdown and links", () => {
        const { root, store } = fixture();
        add(store, "Keep project databases local on Windows.", ["src/storage/store.ts"]);
        const topic = saveMemoryTopic(store, { name: "Storage", prefixes: ["src/storage"], introduction: "Local storage decisions." });
        writeFileSync(join(root, ".code-butler/.gitignore"), "/*\n!/project-summary.md\n");
        const ignore = readFileSync(join(root, ".code-butler/.gitignore"), "utf8");
        const dry = exportMemoryHandbook(store, { dryRun: true });
        expect(dry.memories).toBe(1);
        expect(dry.files).toHaveLength(6);
        expect(existsSync(dry.directory)).toBe(false);
        expect(readFileSync(join(root, ".code-butler/.gitignore"), "utf8")).toBe(ignore);
        const exported = exportMemoryHandbook(store);
        const topicText = readFileSync(join(exported.directory, "topics", topic.id + ".md"), "utf8");
        expect(topicText).toContain("../constraints.md#memory-");
        expect(topicText).toContain("Windows");
        expect(topicText).toContain("Generated by Code Butler");
        const content = readFileSync(join(exported.directory, "constraints.md"), "utf8");
        expect(content).toContain('<a id="memory-');
        expect(content).toContain("src/storage/store.ts");
        expect(exportMemoryHandbook(store).changed).toEqual([]);
        expect(readFileSync(join(exported.directory, "constraints.md"), "utf8")).toBe(content);
        expect(isGeneratedMemoryPath(".code-butler/handbook/constraints.md")).toBe(true);
        expect(isGeneratedMemoryPath(".code-butler/project-summary.md")).toBe(false);
    });
    it("excludes sensitive, private and historical memories without exposing their content", () => {
        const { store } = fixture();
        add(store, "Keep public files under version control.", ["src/public.ts"]);
        add(store, "Sensitive file claim must be excluded.", ["secrets/access.txt"]);
        add(store, "Environment claim must be excluded.", [".env.production"]);
        add(store, "Private device claim must be excluded.", [], "device:11111111-1111-4111-8111-111111111111");
        const old = add(store, "Historical claim must be excluded.");
        store.updateMemoryLifecycle(old.id, { lifecycleStatus: "retracted" });
        const result = exportMemoryHandbook(store);
        expect(result.memories).toBe(1);
        expect(result.excludedMemories).toBe(2);
        const text = result.files.map(path => readFileSync(join(result.directory, path), "utf8")).join("\n");
        expect(text).not.toContain("must be excluded");
    });
    it("preserves Git-ignore rules and exposes only handbook Markdown", () => {
        const { root, store } = fixture();
        execFileSync("git", ["init", "--quiet"], { cwd: root, windowsHide: true });
        const ignorePath = join(root, ".code-butler/.gitignore");
        const custom = "/*\n!/.gitignore\n!/project-summary.md\n!/*.json\n!/backups/\n!/backups/**\n# Keep local fixture artifacts private\n/custom-private\n";
        writeFileSync(ignorePath, custom);
        exportMemoryHandbook(store);
        expect(readFileSync(ignorePath, "utf8")).toContain(custom.trimEnd());
        writeFileSync(join(root, ".code-butler/handbook/data.json"), "{}");
        writeFileSync(join(root, ".code-butler/handbook/private-notes.md"), "Private notes");
        const ignored = execFileSync("git", ["check-ignore", ".code-butler/handbook/data.json", ".code-butler/handbook-export.meta.json"], { cwd: root, encoding: "utf8", windowsHide: true });
        expect(ignored).toContain("data.json");
        expect(ignored).toContain("handbook-export.meta.json");
        const backupDir = join(root, ".code-butler/backups/handbook"); mkdirSync(backupDir, { recursive: true });
        const backup = join(backupDir, "11111111-1111-4111-8111-111111111111.md"); writeFileSync(backup, "Hand-edited backup");
        expect(execFileSync("git", ["check-ignore", ".code-butler/backups/handbook/11111111-1111-4111-8111-111111111111.md"], { cwd: root, encoding: "utf8", windowsHide: true })).toContain("handbook/");
        const visible = execFileSync("git", ["ls-files", "--others", "--exclude-standard"], { cwd: root, encoding: "utf8", windowsHide: true });
        expect(visible).toContain(".code-butler/handbook/index.md");
        expect(visible).not.toContain("meta.json");
        expect(visible).not.toContain("private-notes.md");
        const first = readFileSync(ignorePath, "utf8");
        exportMemoryHandbook(store);
        expect(readFileSync(ignorePath, "utf8")).toBe(first);
    });
    it("backs up edited replacements with force and removes only unchanged obsolete files", () => {
        const { root, store } = fixture();
        const m = add(store, "Keep exports manual.", ["src/memory/export.ts"]);
        let topic = saveMemoryTopic(store, { name: "Exports", prefixes: ["src/memory"] });
        const result = exportMemoryHandbook(store);
        const path = join(result.directory, "constraints.md");
        writeFileSync(path, "Hand-edited content\n");
        expect(() => exportMemoryHandbook(store)).toThrow("edited or unmanaged");
        expect(readFileSync(path, "utf8")).toBe("Hand-edited content\n");
        exportMemoryHandbook(store, { force: true });
        const backupDir = join(root, ".code-butler/backups/handbook");
        expect(readdirSync(backupDir).some(file => readFileSync(join(backupDir, file), "utf8") === "Hand-edited content\n")).toBe(true);
        topic = saveMemoryTopic(store, { id: topic.id, name: topic.name, prefixes: topic.prefixes, expectedRevisions: topic.heads, deleted: true });
        const obsolete = "topics/" + topic.id + ".md";
        expect(exportMemoryHandbook(store).removed).toContain(obsolete);
        expect(existsSync(join(result.directory, obsolete))).toBe(false);
        const second = saveMemoryTopic(store, { name: "Second", prefixes: ["src/memory"] });
        exportMemoryHandbook(store);
        const editedTopic = join(result.directory, "topics", second.id + ".md");
        writeFileSync(editedTopic, "Human-maintained topic\n");
        saveMemoryTopic(store, { id: second.id, name: second.name, prefixes: second.prefixes, expectedRevisions: second.heads, deleted: true });
        expect(() => exportMemoryHandbook(store, { force: true })).toThrow("edited or unmanaged");
        expect(readFileSync(editedTopic, "utf8")).toBe("Human-maintained topic\n");
        expect(store.readMemory(m.id)).toBeDefined();
    });
    it("invalidates generated publications during privacy removal", () => {
        const { root, store } = fixture();
        add(store, "Keep private data out of publications.");
        const result = exportMemoryHandbook(store);
        invalidateHandbookExport(root);
        expect(result.files.every(path => !existsSync(join(result.directory, path)))).toBe(true);
        expect(existsSync(join(root, ".code-butler/handbook-export.meta.json"))).toBe(false);
    });
});
